#!/usr/bin/env python3
"""Splice results/*.txt|md into README.md between the RESULTS markers (nothing typed by hand; a missing file becomes NOT YET MEASURED)."""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def part(title, f, cmd, fence=True, n=None):
    p = os.path.join(ROOT, "results", f)
    if not os.path.exists(p):
        return "### %s\n\nNOT YET MEASURED - run `%s`.\n" % (title, cmd)
    t = open(p).read().rstrip("\n")
    if n:
        t = "\n".join(t.splitlines()[:n])
    return "### %s\n\nFrom `results/%s` (`%s`).\n\n%s\n" % (title, f, cmd, ("```text\n%s\n```" % t) if fence else t)


blocks = [part("Self-checking regression (8 seeds)", "regression.txt", "make seeds", n=3),
          part("As-found RTL against the same testbench", "baseline_original.txt", "make baseline"),
          part("Coverage", "coverage_summary.txt", "make cov"),
          part("Injected-bug campaign", "mutants.txt", "make mutants"),
          part("Synthesis and timing", "ppa.md", "make ppa", fence=False)]
new = "<!-- BEGIN RESULTS (generated by scripts/readme_results.py from results/; do not edit by hand) -->\n\n" + "\n".join(blocks) + "\n<!-- END RESULTS -->"
p = os.path.join(ROOT, "README.md")
old = open(p).read()   # read BEFORE opening for write (open(p, "w") truncates)
open(p, "w").write(re.sub(r"<!-- BEGIN RESULTS.*?<!-- END RESULTS -->", lambda m: new, old, flags=re.S))
print("README results block updated")
